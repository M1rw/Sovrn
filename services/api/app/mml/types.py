"""
MML Types and Contracts

Defines the data structures passed between agents.
"""

from dataclasses import dataclass, field, asdict
from typing import Dict, Any, List, Optional
from enum import Enum


class AgentRole(str, Enum):
    """Roles for MML agents."""
    STRATEGIST = "strategist"  # Understands user intent
    DESIGNER = "designer"      # Creates visual spec
    ARCHITECT = "architect"    # Plans page structure
    BUILDER = "builder"        # Generates code


@dataclass
class BriefAnalysis:
    """
    Output from Strategist Agent.
    Deep understanding of user's request.
    """
    # Core understanding
    business_type: str              # "coffee roastery", "architecture firm", etc.
    brand_personality: str          # "artisan & warm", "bold & minimal", etc.
    target_audience: str            # Who the site is for
    
    # Goals
    primary_goal: str               # Main conversion goal
    secondary_goals: List[str]      # Other objectives
    
    # Content needs
    key_messages: List[str]         # What to communicate
    required_sections: List[str]    # Sections needed
    
    # Design direction
    mood: str                       # "warm", "professional", "edgy", etc.
    visual_style: str               # "craft", "swiss", "dark", etc.
    
    # Special requirements
    special_features: List[str]     # Interactive elements, etc.
    
    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class DesignSpec:
    """
    Output from Designer Agent.
    Complete visual specification.
    """
    # Brand
    brand_name: str
    tagline: str
    
    # Colors
    color_primary: str      # Main brand color
    color_secondary: str    # Supporting color
    color_background: str   # Page background
    color_text: str         # Body text
    color_accent: str       # CTAs, highlights
    color_muted: str        # Secondary text
    
    # Typography
    font_display: str       # Headlines
    font_body: str          # Body text
    font_size_base: str     # Base font size
    heading_weight: int     # Headline weight
    
    # Layout
    layout_style: str       # "full-width", "contained", "asymmetric"
    max_width: str          # Container width
    spacing_unit: str       # Base spacing
    
    # Visual style
    border_radius: str      # Corner rounding
    shadow_style: str       # "none", "subtle", "dramatic"
    image_treatment: str    # How images are styled
    
    # Effects
    hover_style: str        # Hover effects
    transition_speed: str   # Animation speed
    scroll_behavior: str    # Scroll effects
    
    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class Section:
    """A page section."""
    id: str
    type: str               # "hero", "features", "gallery", "cta", etc.
    title: str
    content: Dict[str, Any]
    layout: str = "default"


@dataclass
class PagePlan:
    """
    Output from Architect Agent.
    Complete page structure and content.
    """
    # Navigation
    nav_items: List[str]
    nav_style: str          # "fixed", "sticky", "static"
    
    # Hero
    hero: Dict[str, Any]
    
    # Sections
    sections: List[Section]
    
    # Footer
    footer: Dict[str, Any]
    
    # Interactions
    interactions: List[str]
    
    def to_dict(self) -> Dict[str, Any]:
        return {
            "nav_items": self.nav_items,
            "nav_style": self.nav_style,
            "hero": self.hero,
            "sections": [asdict(s) for s in self.sections],
            "footer": self.footer,
            "interactions": self.interactions
        }


@dataclass
class GeneratedCode:
    """
    Output from Builder Agent.
    Generated HTML/CSS/JS code.
    """
    html: str
    css: str
    js: str
    
    def to_full_html(self) -> str:
        """Combine into single HTML file."""
        return f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>Generated by MML</title>
    <style>
{self.css}
    </style>
</head>
<body>
{self.html}
    <script>
{self.js}
    </script>
</body>
</html>"""


@dataclass
class MMLResult:
    """Complete result from MML pipeline."""
    brief: BriefAnalysis
    spec: DesignSpec
    plan: PagePlan
    code: GeneratedCode
    
    # Metadata
    generation_time_ms: int = 0
    model_used: str = "qwen-coder"
    
    @property
    def html(self) -> str:
        return self.code.to_full_html()
